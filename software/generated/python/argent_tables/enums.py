def mode_mask(active: list[str] | tuple[str, ...]) -> int:
    return sum(1 << TugMode[upper_name(m)] for m in active)


def upper_name(literal: str) -> str:
    return _UPPER.sub('_', literal).replace('-', '_').replace('.', '_').upper()
